"""Models and migrations describe the same schema.

Found in diagnostics: an index the model declared but no migration created
(archived_message_refs.user_id) and two indexes created by migrations but
missing from the models (orders business-state window, support sessions) —
the next autogenerated migration would have dropped them. Defaults and the
SQLite rendering of Enum columns differ by dialect, not by intent, and are
ignored here.
"""
import os
import subprocess
import sys
from pathlib import Path

from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
from sqlalchemy import create_engine

from shop import models as m

ROOT = Path(__file__).resolve().parents[1]


def flatten(diffs):
    for item in diffs:
        yield from (flatten(item) if isinstance(item, list) else [item])


def test_migrations_create_exactly_the_model_schema(tmp_path):
    db = tmp_path / 'schema.db'
    env = {**os.environ, 'DATABASE_URL': f'sqlite+aiosqlite:///{db}'}
    subprocess.run([sys.executable, '-m', 'alembic', 'upgrade', 'head'], cwd=ROOT, env=env, check=True,
                   capture_output=True, text=True)
    with create_engine(f'sqlite:///{db}').connect() as connection:
        diffs = compare_metadata(MigrationContext.configure(connection), m.Base.metadata)
    significant = []
    for diff in flatten(diffs):
        if diff[0] == 'modify_default':
            continue
        if diff[0] == 'modify_type' and diff[2:4] == ('broadcasts', 'status'):
            continue  # SQLite stores the PostgreSQL enum as VARCHAR
        significant.append(diff)
    assert significant == []
