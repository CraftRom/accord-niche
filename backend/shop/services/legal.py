def fill(text: str, values: dict) -> str:
    """Підставляє реквізити. Незаповнене поле не лишає слідів у тексті."""
    def present(key):
        return bool(str(values.get(key) or "").strip())
    out = re.sub(r"\{\{\?(\w+)\}\}(.*?)\{\{/\1\}\}",
                 lambda m: m.group(2) if present(m.group(1)) else "", text, flags=re.S)
    out = re.sub(r"\{\{(\w+)\}\}", lambda m: str(values.get(m.group(1)) or "").strip(), out)
    # Рядки, від яких після підстановки нічого не лишилось.
    out = re.sub(r"\n[ \t]*(?=\n)", "\n", out)
    out = re.sub(r"\n{3,}", "\n\n", out)
    return out.strip() + "\n"


def _date(value) -> str:
    try:
        moment = datetime.fromisoformat(value) if value else None
    except ValueError:
        moment = None
    return (moment or datetime(2026, 11, 19, tzinfo=timezone.utc)).strftime("%d.%m.%Y")


async def read(repo, key: str) -> dict:
    """Збережений текст або початковий шаблон."""
    body_key, at_key, by_key = STORAGE[key]
    raw = await repo.get_settings_map() or {}
    custom = (raw.get(body_key) or "").strip()
    return {"key": key, "title": TITLES[key], "body": custom or DEFAULTS[key].strip() + "\n",
            "is_default": not custom, "updated_at": raw.get(at_key) or None,
            "updated_by": raw.get(by_key) or None}


async def save(repo, key: str, body: str, actor: str) -> dict:
    """Порожній текст повертає початковий шаблон."""
    body_key, at_key, by_key = STORAGE[key]
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    await repo.save_settings_map({body_key: body.strip(), at_key: now, by_key: actor})
    return await read(repo, key)


def render(document: dict, shop) -> str:
    values = seller_values(shop)
    values["UPDATED"] = _date(document.get("updated_at"))
    return fill(document["body"], values)
